#!/usr/bin/env python3
"""Backyard Bash decor (physics-free models, rc_render) written to
assets/maps/backyard_bash/decor.ron: the house back wall, fences and trees beyond them, long
grass along the track edges and wall feet, planting on the raised beds, the hose spiral around
the reel, stepping stones, pebbles and fallen leaves. Everything a car can bump into is a
catalog prop instead (plan.py).

    python3 tools/blender/props/garden/decor.py      (after plan.py; deterministic)

Since the track editor (docs/design/rc_editor.md) the track and decor files are editor-owned: this
script writes them only with --layout, which replaces every edit made in the editor.
"""
import math
import os
import sys
import random

import plan as P

OUT = os.path.join(P.ROOT, 'assets', 'maps', 'backyard_bash', 'decor.ron')
M = 'models/props/garden'


def editor_owned(path):
    """Track and decor files are editor-owned (docs/design/rc_editor.md): this script writes them
    only with --layout, which replaces every edit made in the editor with its own layout."""
    if '--layout' in sys.argv:
        return False
    print(f'skipped {path}: editor-owned (cargo run -p rc_editor); --layout overwrites it')
    return True


def inside(pt, poly):
    x, z = pt
    c = False
    for (ax, az), (bx, bz) in zip(poly, poly[1:] + poly[:1]):
        if (az > z) != (bz > z) and x < ax + (z - az) * (bx - ax) / (bz - az):
            c = not c
    return c


def seg_dist(p, a, b):
    ax, az = a
    dx, dz = b[0] - ax, b[1] - az
    t = max(0.0, min(1.0, ((p[0] - ax) * dx + (p[1] - az) * dz) / max(dx * dx + dz * dz, 1e-9)))
    return math.hypot(p[0] - ax - dx * t, p[1] - az - dz * t)


def edge_dist(pt, poly):
    return min(seg_dist(pt, a, b) for a, b in zip(poly, poly[1:] + poly[:1]))


class Decor:
    def __init__(self):
        self.items = []

    def add(self, model, x, y, z, yaw=0.0, note=''):
        self.items.append((model, x, y, z, (yaw + 180) % 360 - 180, note))

    def write(self):
        lines = ['// Backyard Bash decor — physics-free models (rc_render, crates/rc_render/src/props/',
                 '// decor.rs). GENERATED by tools/blender/props/garden/decor.py — edit that and re-run.',
                 '// House, fences and trees are the backdrop beyond the shell walls; grass, bed plants,',
                 '// the hose spiral, stones and leaves are soft dressing cars pass through.',
                 '(', '    decor: [']
        for model, x, y, z, yaw, note in self.items:
            lines.append(f'        (model: "{M}/{model}.glb", pos: ({P.fmt(x)}, {P.fmt(y)}, '
                         f'{P.fmt(z)}), yaw: {P.fmt(yaw)}),' + (f' // {note}' if note else ''))
        lines += ['    ],', ')', '']
        if editor_owned(OUT):
            return
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, 'w', encoding='utf-8') as fh:
            fh.write('\n'.join(lines))


def wall_flags(p):
    """(wall_left, wall_right) of every dense sample (segment fields are inherited)."""
    cur, out = {'wall_left': False, 'wall_right': False}, []
    for j, (_, _, _, f, _) in enumerate(p.pts):
        cur.update({k: v for k, v in f.items() if k.startswith('wall')})
        end = p.at[j + 1] if j + 1 < len(p.pts) else len(p.dense)
        out += [(cur['wall_left'], cur['wall_right'])] * (end - len(out))
    return out


def main():
    p, i = P.build()
    rng = random.Random(2026)
    d = Decor()
    (x0, z0), (x1, z1) = P.BOUNDS
    ground = P.ground(p, i)
    hard = [g[2] for g in ground if g[0] in ('Stone', 'Wood', 'Water') or g[1] >= P.BED]
    dirt = [g[2] for g in ground if g[0] == 'Dirt' and g[1] < P.BED]
    beds = [g[2] for g in ground if g[1] == P.BED and 'sand' not in g[3]]
    props = P.props(p, i)
    solid = [(x, z, 6.0 if 'deck' in k or 'shed' in k else 3.0) for k, x, _, z, *_ in props
             if not k.endswith(('_ball', 'gnome', 'pot_small', 'can', 'bucket'))]
    coarse = p.dense[::4]

    def on_lawn(x, z, margin=0.0):
        return (x0 + 1 < x < x1 - 1 and z0 + 1 < z < z1 - 1
                and not any(inside((x, z), g) for g in hard)
                and not any(math.hypot(x - sx, z - sz) < r + margin for sx, sz, r in solid))

    def in_corridor(x, z, slack=0.6):
        return any(math.hypot(x - q[0], z - q[2]) < q[4] / 2 - slack for q in coarse)

    # --- backdrop: house, fences, trees beyond the bounds ------------------------------------
    d.add('house', -4.0, 0, z0, 180, 'the house (French doors onto the patio, kitchen door onto the deck)')
    for k, z in enumerate([z0 + 4 + 8 * n for n in range(16)]):
        d.add('fence', x0, 0, z, -90, 'west fence' if k == 0 else '')
        d.add('fence', x1, 0, z, 90, 'east fence' if k == 0 else '')
    for k, x in enumerate([x0 + 4 + 8 * n for n in range(14)]):
        d.add('fence', x, 0, z1, 0, 'south fence' if k == 0 else '')
    for x in (-52.0, -44.0, 36.0, 44.0, 52.0):
        d.add('fence', x, 0, z0, 180, 'north fence beside the house' if x == -52.0 else '')
    for model, x, z, yaw in (('tree_oak', -70, 18, 0), ('tree_oak', -34, 80, 120),
                             ('tree_oak', 44, 82, 200), ('tree_birch', 70, -18, 0),
                             ('tree_birch', -68, -36, 90), ('tree_birch', 12, 76, 40),
                             ('conifer', 70, 30, 0), ('conifer', 68, 44, 50), ('conifer', -70, 50, 10),
                             ('conifer', -66, -56, 0), ('tree_oak', 74, 66, 300)):
        d.add(model, x, 0, z, yaw, 'trees beyond the fences' if (x, z) == (-70, 18) else '')
    # --- the hose spiral around the reel -------------------------------------------------------
    for kind, x, _, z, yaw, _, _ in props:
        if kind == 'garden_hose_reel':
            d.add('hose_spiral', x, 0, z, yaw, 'hose unrolled around the reel (continues its end)')
    # --- long grass along the track edges and the wall feet -----------------------------------
    walls = wall_flags(p)
    tufts = ('tuft_small', 'tuft', 'tuft', 'tuft_large')
    first = True
    for k in range(0, len(p.dense), 5):
        x, _, z, h, w = p.dense[k]
        rx, rz = P.right_of(h)
        for side in (-1, 1):
            wall = walls[k][0 if side < 0 else 1]
            lat = side * (w / 2 - 0.45 if wall else w / 2 + rng.uniform(0.2, 2.6))
            if wall and rng.random() < 0.45:
                continue
            tx, tz = x + rx * lat + rng.uniform(-0.6, 0.6), z + rz * lat + rng.uniform(-0.6, 0.6)
            if not on_lawn(tx, tz, 0.5) or (not wall and in_corridor(tx, tz)):
                continue
            if any(inside((tx, tz), g) for g in dirt):
                continue
            d.add(rng.choice(tufts), tx, P.LAWN, tz, rng.uniform(0, 360),
                  'long grass along the track edges and wall feet' if first else '')
            first = False
    # tufts along the fences and the outer lawn edges
    for n in range(70):
        side = rng.choice(('w', 'e', 's'))
        if side == 'w':
            x, z = x0 + rng.uniform(1.0, 3.0), rng.uniform(z0 + 2, z1 - 2)
        elif side == 'e':
            x, z = x1 - rng.uniform(1.0, 3.5), rng.uniform(z0 + 2, z1 - 2)
        else:
            x, z = rng.uniform(x0 + 2, x1 - 2), z1 - rng.uniform(1.0, 2.5)
        if on_lawn(x, z, 0.3) and not in_corridor(x, z, -1.0):
            d.add(rng.choice(tufts), x, P.LAWN, z, rng.uniform(0, 360), 'fence-line grass' if n == 0 else '')
    # a flower border along the east fence (low plants only: cars can reach it)
    for n in range(14):
        x, z = x1 - rng.uniform(2.5, 4.5), -24 + n * 5.6 + rng.uniform(-1, 1)
        if on_lawn(x, z, 0.5) and not in_corridor(x, z, -1.5):
            d.add(rng.choice(('daisies', 'fern', 'hosta', 'tuft_large')), x, P.LAWN, z,
                  rng.uniform(0, 360), 'east border' if n == 0 else '')
    # clover and short grass scattered over the open lawn (breaks up the flat green)
    n = 0
    while n < 90:
        x, z = rng.uniform(x0 + 3, x1 - 3), rng.uniform(z0 + 3, z1 - 3)
        if not on_lawn(x, z, 0.5) or any(inside((x, z), g) for g in dirt + beds):
            continue
        d.add(rng.choice(('clover', 'clover', 'tuft_small')), x, P.LAWN, z, rng.uniform(0, 360),
              'clover and short grass over the lawn' if n == 0 else '')
        n += 1
    # --- planting on the raised beds ----------------------------------------------------------
    plants = ('hydrangea', 'hosta', 'fern', 'daisies', 'ornamental_grass', 'tuft_large', 'hydrangea')
    placed = []
    for bed in beds:
        xs, zs = [q[0] for q in bed], [q[1] for q in bed]
        tries = 0
        while tries < 900:
            tries += 1
            x, z = rng.uniform(min(xs), max(xs)), rng.uniform(min(zs), max(zs))
            if not inside((x, z), bed) or edge_dist((x, z), bed) < 1.4:
                continue
            if any(math.hypot(x - a, z - b) < 2.8 for a, b in placed):
                continue
            placed.append((x, z))
            d.add(rng.choice(plants), x, P.BED, z, rng.uniform(0, 360),
                  'raised-bed planting' if len(placed) == 1 else '')
    # --- wet mud around the puddles, stones, pebbles, leaves -----------------------------------
    for k, (cx, cz, _, _) in enumerate(P.PUDDLES):
        d.add(f'puddle_rim_{k + 1}', cx, P.DIRT, cz, 0, 'wet mud around the puddles' if k == 0 else '')
    for k, (x, z) in enumerate(((-6.5, 27.5), (-5.6, 30.6), (-4.4, 33.7), (-3.6, 36.9),
                                (-2.9, 40.0), (40.2, 50.5), (38.4, 47.6))):
        d.add('stepping_stone', x, P.LAWN, z, rng.uniform(0, 360), 'stepping stones' if k == 0 else '')
    for k, (x, z) in enumerate(((39.5, 58.0), (52.5, 49.0), (7.5, 55.5), (-49.0, 39.5))):
        d.add('pebbles', x, P.LAWN, z, rng.uniform(0, 360), 'pebbles' if k == 0 else '')
    n = 0
    while n < 32:
        x, z = rng.uniform(x0 + 3, x1 - 3), rng.uniform(z0 + 3, z1 - 3)
        y = P.DECK if inside((x, z), ground[2][2]) else P.PATIO if inside((x, z), ground[1][2]) \
            else P.DIRT if any(inside((x, z), g) for g in dirt) else P.LAWN
        if any(inside((x, z), g) for g in beds) or any(math.hypot(x - sx, z - sz) < r
                                                       for sx, sz, r in solid):
            continue
        d.add('leaves', x, y, z, rng.uniform(0, 360), 'fallen leaves' if n == 0 else '')
        n += 1
    d.write()
    print(f'{len(d.items)} decor items')


if __name__ == '__main__':
    main()
