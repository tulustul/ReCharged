//! `--calibrate-medals` (GDD §9): every layout (forward/reverse × mirror) of every catalog track
//! that has a track file is raced headless in Time Trial by the Elite autopilot in a Phantom
//! (3 laps, items and catch-up off). The median time of [`SEEDS`] becomes the layout's
//! `reference_secs` in `assets/data/medals.ron`; tracks without a file keep their old entries.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use bevy::prelude::*;
use rc_core::prelude::*;
use rc_game::{MEDALS_FILE, Medal, MedalTable, variant_key};

use crate::headless;

/// The car of the reference driver (GDD §9).
const CAR: &str = "phantom";
/// One run per seed; the median is the reference (seeds vary the AI's mistakes by ~2 %).
const SEEDS: [u64; 3] = [1, 2, 3];
/// Forward/reverse × mirror.
const LAYOUTS: [(bool, bool); 4] = [(false, false), (true, false), (false, true), (true, true)];

const HEADER: &str = "\
// Time Trial medal reference times (GDD §9): seconds for 3 laps by an Elite AI in a Phantom,
// items and catch-up off. Medal targets = reference x Platinum 0.95, Gold 0.98, Silver 1.05,
// Bronze 1.15. Keys: <track>[_rev][_mirror] (rc_game::variant_key).
// Generated by `recharged --calibrate-medals` (median of seeds 1-3); rerun it after changing a track,
// the AI or the Phantom.
";

pub fn run(paths: UserPaths) -> AppExit {
    headless::init_logging();
    let catalog = match Catalog::load(&paths.assets_dir) {
        Ok(catalog) => catalog,
        Err(e) => {
            eprintln!("--calibrate-medals: {e}");
            return AppExit::error();
        }
    };
    let file = paths.assets_dir.join(MEDALS_FILE);
    let mut references = old_references(&std::fs::read_to_string(&file).unwrap_or_default());
    // Private saves: Time Trial ghosts and records never reach a real profile.
    let data_dir = std::env::temp_dir().join(format!("recharged-calibrate-{}", std::process::id()));
    let mut notes = Vec::new();
    println!(
        "{:<26}{:>27}{:>11}{:>9}{:>9}{:>9}{:>9}",
        "layout", "runs s", "reference", "plat", "gold", "silver", "bronze"
    );
    for track in &catalog.tracks {
        let track_file =
            rc_track::map_dir(&paths.assets_dir, track.id.as_str()).join(rc_track::TRACK_FILE);
        if !track_file.is_file() {
            notes.push(format!("{}: no track file, old entries kept", track.id));
            continue;
        }
        for (reverse, mirror) in LAYOUTS {
            let variant = TrackVariant {
                track: track.id.clone(),
                reverse,
                mirror,
            };
            let key = variant_key(&variant);
            let runs: Result<Vec<f32>, String> = SEEDS
                .iter()
                .map(|&seed| reference_run(&variant, seed, &paths.assets_dir, &data_dir))
                .collect();
            match runs {
                Ok(mut runs) => {
                    let shown = runs.iter().map(|s| format!("{s:.2}")).collect::<Vec<_>>();
                    runs.sort_by(f32::total_cmp);
                    let reference = runs[runs.len() / 2];
                    references.insert(key.clone(), reference);
                    let targets =
                        Medal::BEST_FIRST.map(|m| format!("{:.2}", reference * m.factor()));
                    println!(
                        "{key:<26}{:>27}{reference:>11.2}{:>9}{:>9}{:>9}{:>9}",
                        shown.join(" "),
                        targets[0],
                        targets[1],
                        targets[2],
                        targets[3]
                    );
                }
                Err(e) => notes.push(format!("{key}: FAILED ({e}), old entry kept")),
            }
        }
    }
    let _ = std::fs::remove_dir_all(&data_dir);
    for note in &notes {
        println!("note: {note}");
    }
    let text = medals_ron(&references);
    if let Err(e) = MedalTable::parse(&text) {
        eprintln!("--calibrate-medals: generated an invalid file: {e}");
        return AppExit::error();
    }
    if let Err(e) = std::fs::write(&file, text) {
        eprintln!("--calibrate-medals: {}: {e}", file.display());
        return AppExit::error();
    }
    println!("wrote {}", file.display());
    match notes.iter().any(|n| n.contains("FAILED")) {
        true => AppExit::error(),
        false => AppExit::Success,
    }
}

/// One Time Trial by the autopilot; its finish time in seconds.
fn reference_run(
    variant: &TrackVariant,
    seed: u64,
    assets_dir: &std::path::Path,
    data_dir: &std::path::Path,
) -> Result<f32, String> {
    let config = AutomationConfig {
        unlock_all: true,
        headless_race: true,
        quick_race: Some(QuickRaceArgs {
            track: variant.track.clone(),
            reverse: variant.reverse,
            mirror: variant.mirror,
            car: Some(CarId::new(CAR)),
            seed: Some(seed),
            mode: QuickRaceMode::TimeTrial,
            ..default()
        }),
        ..default()
    };
    let paths = UserPaths {
        assets_dir: assets_dir.to_owned(),
        data_dir: data_dir.to_owned(),
    };
    let done = headless::run_race(&mut headless::app(config, paths))?;
    let c = &done.config;
    if c.laps != 3 || c.items || c.ai_catch_up || c.racers.len() != 1 {
        return Err(format!(
            "not a reference setup: {} laps, items {}, catch-up {}, {} racers",
            c.laps,
            c.items,
            c.ai_catch_up,
            c.racers.len()
        ));
    }
    match done.results.entries.first() {
        Some(e) if e.finished => Ok(ticks_to_secs(e.time_ticks)),
        _ => Err(format!("seed {seed}: the autopilot did not finish")),
    }
}

/// `"key": seconds` pairs of an existing medal file.
// ponytail: reads the one-entry-per-line layout this tool writes; parse with ron if hand edits
// ever reformat the file.
fn old_references(text: &str) -> BTreeMap<String, f32> {
    text.lines()
        .filter_map(|line| {
            let (key, secs) = line.split("//").next()?.split_once(':')?;
            let key = key.trim().strip_prefix('"')?.strip_suffix('"')?;
            Some((
                key.to_owned(),
                secs.trim().trim_end_matches(',').parse().ok()?,
            ))
        })
        .collect()
}

/// The medal file for `references`.
fn medals_ron(references: &BTreeMap<String, f32>) -> String {
    let mut text = format!("{HEADER}(\n    reference_secs: {{\n");
    for (key, secs) in references {
        let _ = writeln!(text, "        \"{key}\": {secs:.2},");
    }
    text.push_str("    },\n)\n");
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn medal_files_round_trip_through_rc_game() {
        let refs = BTreeMap::from([
            ("toy_town".to_owned(), 74.68),
            ("toy_town_rev".to_owned(), 80.0),
        ]);
        let text = medals_ron(&refs);
        assert_eq!(old_references(&text), refs);
        let table = MedalTable::parse(&text).expect("rc_game reads it");
        let gold = table
            .targets(&TrackVariant::forward("toy_town"))
            .expect("calibrated")
            .target(Medal::Gold);
        assert_eq!(gold, secs_to_ticks(74.68 * 0.98));
    }

    #[test]
    fn the_shipped_medal_file_is_readable() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../assets")
            .join(MEDALS_FILE);
        let text = std::fs::read_to_string(path).expect("medals.ron");
        assert!(old_references(&text).len() >= 4, "{text}");
    }
}
