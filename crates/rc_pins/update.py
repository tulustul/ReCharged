#!/usr/bin/env python3
"""Regenerate crates/rc_pins/Cargo.toml so every workspace member compiles exactly the same
third-party units as the whole workspace (one shared build of Bevy instead of one per `-p` set).

Run after changing dependencies:  python3 crates/rc_pins/update.py
Stdlib only. Reads Cargo's unit graph (`--unit-graph`, unlocked with RUSTC_BOOTSTRAP=1; nothing
is compiled). Target units are pinned in [dependencies], host units (build scripts, proc macros
and their dependencies) in [build-dependencies].
"""
import collections
import hashlib
import json
import os
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "crates/rc_pins/Cargo.toml"
HEADER = """\
[package]
name = "rc_pins"
version.workspace = true
edition.workspace = true
license.workspace = true
publish.workspace = true
description = "Build hygiene only: pins third-party features to what the full game resolves."

# Why: Cargo resolves features per build invocation, so `cargo test -p rc_core` and
# `cargo build -p recharged` used to resolve e.g. `glam`/`uuid` with different features and each
# compiled its own copy of Bevy (+2.5 min, +1.4 GB per distinct set). rc_core depends on this crate,
# so every member resolves the same features as the full workspace and reuses one shared build.
# GENERATED by `python3 crates/rc_pins/update.py` (run it after dependency changes).
# No code may use these crates through this package.

[lints]
workspace = true
"""


def cargo(*args, env=None):
    return subprocess.run(["cargo", *args], cwd=ROOT, capture_output=True, text=True, check=True,
                          env=env).stdout


def unit_graph(*select):
    env = dict(os.environ, RUSTC_BOOTSTRAP="1")
    out = cargo("build", "--unit-graph", "-Z", "unstable-options", "--all-targets", *select, env=env)
    units = json.loads(out)["units"]
    host = set()
    stack = [d["index"] for u in units
             if "proc-macro" in u["target"]["kind"] or "custom-build" in u["target"]["kind"]
             for d in u["dependencies"]]
    stack += [i for i, u in enumerate(units) if "proc-macro" in u["target"]["kind"]]
    while stack:
        i = stack.pop()
        if i not in host:
            host.add(i)
            stack.extend(d["index"] for d in units[i]["dependencies"])
    memo = {}

    def identity(i):
        if i not in memo:
            u = units[i]
            own = json.dumps([u["pkg_id"], u["target"]["name"], u["target"]["kind"], u["mode"],
                              u["features"], u["profile"], u["platform"]], sort_keys=True)
            deps = sorted(identity(d["index"]) for d in u["dependencies"])
            memo[i] = hashlib.sha1((own + "".join(deps)).encode()).hexdigest()
        return memo[i]

    return units, host, identity


def package_key(pkg_id):
    # "registry+https://...#name@1.2.3" -> "name v1.2.3"
    name_ver = pkg_id.rsplit("#", 1)[1]
    name, ver = name_ver.rsplit("@", 1)
    return f"{name} v{ver}"


def differences(member, full_units, full_host, full_identity):
    """{(package, is_host): features of the full build} for every root cause of divergence."""
    full_ids = {full_identity(i) for i in range(len(full_units))}
    features = collections.defaultdict(set)
    for i, u in enumerate(full_units):
        features[(u["pkg_id"], i in full_host)] |= set(u["features"])
    units, host, identity = unit_graph("-p", member)
    out = {}
    for i, u in enumerate(units):
        if u["pkg_id"].startswith("path+") or identity(i) in full_ids:
            continue
        if "custom-build" in u["target"]["kind"]:
            continue  # a build script follows the features of the library it belongs to
        deps_ok = all(identity(d["index"]) in full_ids
                      or units[d["index"]]["pkg_id"].startswith("path+")
                      or units[d["index"]]["pkg_id"] == u["pkg_id"]  # its own build script
                      for d in u["dependencies"])
        if deps_ok:  # the unit itself differs: its features diverge
            key = (u["pkg_id"], i in host)
            out[(package_key(u["pkg_id"]), i in host)] = features.get(key, set(u["features"]))
    return out


def dep_line(key, feats):
    name, ver = key.split()
    ver = ver.lstrip("v")
    major = ver.split(".")
    alias = name.replace("-", "_") + "_" + (major[0] if major[0] != "0" else "0_" + major[1])
    parts = [f'package = "{name}"', f'version = "{ver}"']
    if "default" not in feats:
        parts.append("default-features = false")
    named = [f for f in sorted(feats) if f != "default"]
    if named:
        parts.append("features = [" + ", ".join(f'"{f}"' for f in named) + "]")
    return f"{alias} = {{ {', '.join(parts)} }}"


def render(pins):
    text = HEADER
    for title, is_host in (("[dependencies]", False), ("[build-dependencies]", True)):
        keys = sorted(k for (k, h) in pins if h == is_host)
        text += f"\n{title}\n" + "".join(dep_line(k, pins[(k, is_host)]) + "\n" for k in keys)
    return text


def main():
    pins = {}
    MANIFEST.write_text(render(pins))  # start clean so stale pins disappear
    meta = json.loads(cargo("metadata", "--no-deps", "--format-version", "1"))
    members = [p["name"] for p in meta["packages"] if p["name"] != "rc_pins"]
    for round_ in range(1, 8):
        full = unit_graph("--workspace")
        missing = {}
        for member in members:
            missing.update(differences(member, *full))
        print(f"round {round_}: {len(missing)} root unit(s) differ: "
              f"{sorted(f'{k}{' (host)' if h else ''}' for k, h in missing)}")
        if not missing:
            print(f"converged: {len(pins)} pins in {MANIFEST.relative_to(ROOT)}")
            return
        for key, feats in missing.items():
            pins[key] = set(pins.get(key, set())) | set(feats)
        MANIFEST.write_text(render(pins))
    raise SystemExit("did not converge; inspect the differences manually")


if __name__ == "__main__":
    main()
