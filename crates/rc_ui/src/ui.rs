//! `ui.*` channels: readiness and render errors of the React app, the screen it shows
//! (`ui.screen`, logged and waited on by `--input-script`), UI sound cues and music stingers, menu
//! navigation (`ui.nav`), toasts, the FPS meter and the F12 profiler (`ui.perf`), plus the
//! readiness watchdog.

use bevy::diagnostic::DiagnosticsStore;
use bevy::input::gamepad::Gamepad;
use bevy::prelude::*;
use bevy::window::{CursorMoved, CursorOptions, PrimaryWindow};
use bevy_react::prelude::*;
use rc_core::prelude::*;
use rc_game::GameNotice;

use crate::input::UiDeviceKind;
use crate::profile::{UiUnlockedItem, Unlocked};

/// `ui.ready` must arrive this many seconds after start, or the run is reported as broken.
pub const READY_TIMEOUT_SECS: f32 = 15.0;

/// The same cue within this many seconds plays once (a fast pointer sweep over a list).
const CUE_RETRIGGER_SECS: f64 = 0.04;

/// The FPS meter and the profiler average this many seconds (and update as often).
const FPS_WINDOW_SECS: f64 = 0.5;

/// The full profiler leaves out diagnostics without a measurement this recent.
const STALE: std::time::Duration = std::time::Duration::from_secs(1);

/// React → Bevy message `ui.ready`: the React app mounted (again after a full hot reload).
#[react_message(name = "ui.ready")]
pub struct UiReady;

/// React → Bevy message `ui.error`: the top-level ErrorBoundary caught a render error.
#[react_message(name = "ui.error")]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
pub struct UiError {
    /// Error message.
    pub message: String,
    /// Component stack, if React provided one.
    #[ts(optional)]
    pub stack: Option<String>,
}

/// React → Bevy message `ui.screen`: the screen React shows changed — a menu route (`title`,
/// `main`, `trackSelect` …), `loading`, or the race layer's view (`race`, `pause`, `results`,
/// `standings`, `score`, `changeTrack`).
#[react_message(name = "ui.screen")]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
pub struct UiScreen {
    /// Screen id.
    pub screen: String,
}

mirror_enum!(
    /// [`UiCue`]: a UI sound.
    UiCueName = UiCue { Hover, Select, Back, Toggle, SliderTick, Error, Unlock }
);

/// React → Bevy message `ui.sound`: play a UI cue (focus, confirm, back, toggle, …).
#[react_message(name = "ui.sound")]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
pub struct PlayCue {
    /// The cue.
    pub cue: UiCueName,
}

/// A music stinger the UI times (the Cup-end ceremony).
#[derive(serde::Deserialize, ts_rs::TS, Debug, Clone, Copy, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
pub enum UiStinger {
    /// 2nd or 3rd in the cup.
    PodiumFanfare,
    /// Won the cup.
    CupVictory,
}

/// React → Bevy message `ui.stinger`: play a music stinger (`MusicStinger`).
#[react_message(name = "ui.stinger")]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
pub struct PlayStinger {
    /// The stinger.
    pub stinger: UiStinger,
}

mirror_enum!(
    /// [`NavAction`]: one menu navigation step.
    UiNavAction = NavAction { Up, Down, Left, Right, Confirm, Back, PrevTab, NextTab }
);

/// Bevy → React event `ui.nav`: a menu navigation step (rc_input's `UiNav`). The only source of
/// keyboard/gamepad navigation in React.
#[react_event(name = "ui.nav")]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct NavEvent {
    /// The step.
    pub action: UiNavAction,
    /// Player slot 0–3 (`null` = a device not assigned to a slot, e.g. before joining).
    pub slot: Option<u8>,
    /// Device family (button glyphs follow it).
    pub device: UiDeviceKind,
    /// Generated by hold-repeat.
    pub repeat: bool,
}

impl From<&UiNav> for NavEvent {
    fn from(nav: &UiNav) -> Self {
        Self {
            action: nav.action.into(),
            slot: nav.slot.map(|s| s.0),
            device: nav.device.into(),
            repeat: nav.repeat,
        }
    }
}

/// Bevy → React event `toast`: rc_game's notices (unlocks travel as `profile.unlocked`). React
/// owns the wording and shows errors and disconnects as dialogs, the rest as toasts.
#[react_event(name = "toast")]
#[serde(tag = "kind", rename_all = "camelCase")]
#[ts(tag = "kind", rename_all = "camelCase")]
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum UiNotice {
    /// A Golden Battery was collected (and saved).
    GoldenBattery {
        /// Track id.
        track: String,
    },
    /// A layout's records were set on another version of the track and were discarded.
    RecordsDiscarded {
        /// Track id.
        track: String,
        /// Reverse layout.
        reverse: bool,
        /// Mirrored.
        mirror: bool,
    },
    /// A player's controller disconnected; the race is paused.
    ControllerDisconnected {
        /// Slot 0–3.
        slot: u8,
    },
    /// A race could not start or load, or data is broken; the game is in the menu.
    Error {
        /// What went wrong (file, field).
        detail: String,
    },
    /// A save failed (retried with the next save).
    SaveFailed {
        /// The cause.
        detail: String,
    },
    /// A corrupt save was moved aside and defaults are used.
    SaveRestored {
        /// The corrupt file.
        file: String,
        /// Where it was moved.
        backup: Option<String>,
    },
}

/// Bevy → React event `ui.perf`: every [`FPS_WINDOW_SECS`] while the FPS meter setting or the
/// profiler is on, and at once when F12 / F11 toggle the profiler.
#[react_event(name = "ui.perf")]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
#[derive(Debug, Clone, PartialEq)]
pub struct UiPerf {
    /// Frames per second over the last window, rounded.
    pub fps: u16,
    /// The profiler's readout; `null` while it is closed (the FPS meter shows `fps` alone).
    pub profiler: Option<UiProfiler>,
}

/// The profiler: F12 opens the compact readout, F11 expands it to every Bevy diagnostic.
#[derive(serde::Serialize, ts_rs::TS, Debug, Clone, PartialEq)]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
pub struct UiProfiler {
    /// Main-world CPU time per frame, ms (`rc_core::perf::CPU_FRAME_MS`).
    pub cpu_ms: Option<f32>,
    /// GPU time per frame, ms (`null` without timestamp queries).
    pub gpu_ms: Option<f32>,
    /// Entities the active cameras draw (summed over cameras; shadow views excluded).
    pub visible: Option<u32>,
    /// Draw calls of the camera views (`rc_core::perf::DRAW_CALLS`).
    pub draws: Option<u32>,
    /// Draw calls of the shadow views.
    pub shadow_draws: Option<u32>,
    /// Every Bevy diagnostic measured in the last second, by path; empty unless expanded.
    pub diagnostics: Vec<UiDiagnostic>,
}

/// One Bevy diagnostic: its average over the recorded history.
#[derive(serde::Serialize, ts_rs::TS, Debug, Clone, PartialEq)]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
pub struct UiDiagnostic {
    /// `render/frame/elapsed_gpu`, `fps` …
    pub path: String,
    /// The value.
    pub value: f32,
    /// Unit (`ms`, `%` or empty).
    pub suffix: String,
}

/// What the profiler shows: F12 toggles it, F11 toggles the full diagnostics list.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub(crate) enum ProfilerView {
    #[default]
    Closed,
    Compact,
    Full,
}

impl ProfilerView {
    fn toggled(self, key: KeyCode) -> Self {
        match (key, self) {
            (KeyCode::F12, Self::Closed) => Self::Compact,
            (KeyCode::F12, _) => Self::Closed,
            (KeyCode::F11, Self::Full) => Self::Compact,
            (KeyCode::F11, _) => Self::Full,
            (_, view) => view,
        }
    }
}

/// Health of the React UI; automation runs exit non-zero when it is not ready or has errors.
#[derive(Resource, Debug, Clone, Default, PartialEq, Eq)]
pub struct UiStatus {
    /// `ui.ready` arrived.
    pub ready: bool,
    /// `ui.error` messages received.
    pub errors: u32,
    /// The screen React reported last (`ui.screen`).
    pub screen: String,
}

pub(crate) fn register(app: &mut App) {
    app.add_react_handler(on_ready)
        .add_react_handler(on_error)
        .add_react_handler(on_screen)
        .add_react_handler(on_cue)
        .add_react_handler(
            |stinger: On<PlayStinger>, mut out: MessageWriter<MusicStinger>| {
                out.write(MusicStinger(match stinger.event().stinger {
                    UiStinger::PodiumFanfare => MusicCue::PodiumFanfare,
                    UiStinger::CupVictory => MusicCue::CupVictory,
                }));
            },
        )
        .add_react_event::<NavEvent>()
        .add_react_event::<UiNotice>()
        .add_react_event::<UiPerf>();
}

fn on_ready(_: On<UiReady>, status: Option<ResMut<UiStatus>>) {
    if let Some(mut status) = status {
        if !status.ready {
            info!("UI ready");
        }
        status.ready = true;
    }
}

fn on_error(error: On<UiError>, status: Option<ResMut<UiStatus>>) {
    let error = error.event();
    error!(
        "UI error: {}\n{}",
        error.message,
        error.stack.as_deref().unwrap_or("")
    );
    if let Some(mut status) = status {
        status.errors += 1;
    }
}

fn on_screen(screen: On<UiScreen>, status: Option<ResMut<UiStatus>>) {
    let screen = &screen.event().screen;
    if let Some(mut status) = status.filter(|s| s.screen != *screen) {
        info!("UI screen: {screen}");
        status.screen.clone_from(screen);
    }
}

fn on_cue(
    cue: On<PlayCue>,
    time: Res<Time<Real>>,
    mut last: Local<Vec<(UiCue, f64)>>,
    mut out: MessageWriter<UiSound>,
) {
    let cue = UiCue::from(cue.event().cue);
    let now = time.elapsed_secs_f64();
    match last.iter_mut().find(|(c, _)| *c == cue) {
        Some((_, at)) if now - *at < CUE_RETRIGGER_SECS => return,
        Some((_, at)) => *at = now,
        None => last.push((cue, now)),
    }
    out.write(UiSound(cue));
}

/// Forwards rc_input's `UiNav` to React as `ui.nav`.
pub(crate) fn forward_nav(mut navs: MessageReader<UiNav>, events: ReactEvents) {
    for nav in navs.read() {
        events.send(&NavEvent::from(nav));
    }
}

/// Hides the OS cursor after keyboard or gamepad input and shows it again once the mouse really
/// moves (a resting pointer neither shows nor steals the keyboard/pad focus; React moves the focus
/// on pointer motion only).
pub(crate) fn cursor_visibility(
    mut moved: MessageReader<CursorMoved>,
    mut navs: MessageReader<UiNav>,
    keys: Option<Res<ButtonInput<KeyCode>>>,
    pads: Query<&Gamepad>,
    mut cursors: Query<&mut CursorOptions, With<PrimaryWindow>>,
) {
    // A cursor entering the window has no delta: only motion inside it counts.
    let moved = moved
        .read()
        .any(|m| m.delta.is_some_and(|d| d != Vec2::ZERO));
    let pressed = navs.read().count() > 0
        || keys.is_some_and(|k| k.get_just_pressed().next().is_some())
        || pads.iter().any(|p| p.get_just_pressed().next().is_some());
    let visible = match (moved, pressed) {
        (true, _) => true,
        (false, true) => false,
        (false, false) => return,
    };
    for mut cursor in &mut cursors {
        if cursor.visible != visible {
            cursor.visible = visible;
        }
    }
}

/// Forwards rc_game's notices: unlocks as one `profile.unlocked` per frame, the rest as `toast`.
/// Boot-time notices arrive before React listens, so everything waits for `ui.ready`.
pub(crate) fn forward_notices(
    mut notices: MessageReader<GameNotice>,
    status: Res<UiStatus>,
    mut held: Local<Vec<GameNotice>>,
    events: ReactEvents,
) {
    held.extend(notices.read().cloned());
    if !status.ready || held.is_empty() {
        return;
    }
    let mut unlocked = Vec::new();
    for notice in std::mem::take(&mut *held) {
        let toast = match notice {
            GameNotice::Unlocked(content) => {
                unlocked.push(UiUnlockedItem::from(&content));
                continue;
            }
            GameNotice::GoldenBattery(track) => UiNotice::GoldenBattery { track: track.0 },
            GameNotice::RecordsDiscarded(variant) => UiNotice::RecordsDiscarded {
                track: variant.track.0,
                reverse: variant.reverse,
                mirror: variant.mirror,
            },
            GameNotice::ControllerDisconnected(slot) => {
                UiNotice::ControllerDisconnected { slot: slot.0 }
            }
            GameNotice::Error(detail) => UiNotice::Error { detail },
            GameNotice::SaveFailed(detail) => UiNotice::SaveFailed { detail },
            GameNotice::SaveRestored { file, backup } => UiNotice::SaveRestored { file, backup },
        };
        events.send(&toast);
    }
    if !unlocked.is_empty() {
        events.send(&Unlocked { items: unlocked });
    }
}

/// Counts frames and sends `ui.perf` at the end of each window while the FPS meter or the
/// profiler is on (frames are counted either way, so the first value after switching the meter on
/// is a full window's), and at once when F12 / F11 change the profiler.
pub(crate) fn push_perf(
    time: Res<Time<Real>>,
    settings: Option<Res<Settings>>,
    keys: Option<Res<ButtonInput<KeyCode>>>,
    store: Option<Res<DiagnosticsStore>>,
    mut view: Local<ProfilerView>,
    mut window: Local<(u32, f64, u16)>,
    events: ReactEvents,
) {
    let before = *view;
    if let Some(keys) = keys {
        for key in keys.get_just_pressed() {
            *view = view.toggled(*key);
        }
    }
    window.0 += 1;
    let now = time.elapsed_secs_f64();
    let secs = now - window.1;
    if secs >= FPS_WINDOW_SECS {
        let fps = (f64::from(window.0) / secs).round() as u16;
        *window = (0, now, fps);
    } else if *view == before {
        return;
    }
    let meter = settings.is_some_and(|s| s.gameplay.fps_meter);
    if !meter && *view == ProfilerView::Closed && before == ProfilerView::Closed {
        return;
    }
    events.send(&UiPerf {
        fps: window.2,
        profiler: (*view != ProfilerView::Closed)
            .then(|| profiler(store.as_deref(), *view == ProfilerView::Full)),
    });
}

fn profiler(store: Option<&DiagnosticsStore>, full: bool) -> UiProfiler {
    let average = |path| {
        store
            .and_then(|s| s.get(path))
            .and_then(|d| d.average())
            .filter(|v| v.is_finite())
            .map(|v| v as f32)
    };
    let mut diagnostics: Vec<UiDiagnostic> = match store {
        Some(store) if full => store
            .iter()
            // A pass that stopped running (e.g. the environment map filter) keeps its history.
            .filter(|d| d.measurement().is_some_and(|m| m.time.elapsed() < STALE))
            .filter_map(|d| {
                let value = d.average().filter(|v| v.is_finite())?;
                Some(UiDiagnostic {
                    path: d.path().as_str().to_owned(),
                    value: value as f32,
                    suffix: d.suffix.to_string(),
                })
            })
            .collect(),
        _ => Vec::new(),
    };
    diagnostics.sort_by(|a, b| a.path.cmp(&b.path));
    UiProfiler {
        cpu_ms: average(&perf::CPU_FRAME_MS),
        gpu_ms: average(&perf::GPU_FRAME_MS),
        visible: average(&perf::VISIBLE_ENTITIES).map(|v| v.round() as u32),
        draws: average(&perf::DRAW_CALLS).map(|v| v.round() as u32),
        shadow_draws: average(&perf::SHADOW_DRAW_CALLS).map(|v| v.round() as u32),
        diagnostics,
    }
}

/// Logs an error (and ends automated runs with a failure) when `ui.ready` is late.
pub(crate) fn watchdog(
    time: Res<Time<Real>>,
    status: Res<UiStatus>,
    automation: Option<Res<AutomationConfig>>,
    mut reported: Local<bool>,
    mut exit: MessageWriter<AppExit>,
) {
    if status.ready || *reported || time.elapsed_secs() < READY_TIMEOUT_SECS {
        return;
    }
    *reported = true;
    error!(
        "ui.ready did not arrive within {READY_TIMEOUT_SECS} s (UI bundle missing, threw, or not mounted)"
    );
    if automation.is_some_and(|a| a.is_automated()) {
        exit.write(AppExit::error());
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn f12_toggles_the_profiler_and_f11_its_full_view() {
        use ProfilerView::*;
        let press = |keys: &[KeyCode]| keys.iter().fold(Closed, |v, k| v.toggled(*k));
        assert_eq!(press(&[KeyCode::F12]), Compact);
        assert_eq!(press(&[KeyCode::F12, KeyCode::F12]), Closed);
        assert_eq!(press(&[KeyCode::F11]), Full, "F11 opens it expanded");
        assert_eq!(press(&[KeyCode::F12, KeyCode::F11, KeyCode::F11]), Compact);
        assert_eq!(press(&[KeyCode::F11, KeyCode::F12]), Closed);
        assert_eq!(press(&[KeyCode::KeyA]), Closed);
    }

    #[test]
    fn the_cursor_hides_on_key_and_pad_navigation_and_shows_when_the_mouse_moves() {
        let mut app = App::new();
        app.add_message::<CursorMoved>()
            .add_message::<UiNav>()
            .add_systems(Update, cursor_visibility);
        let window = app
            .world_mut()
            .spawn((PrimaryWindow, CursorOptions::default()))
            .id();
        let visible = |app: &App| app.world().get::<CursorOptions>(window).map(|c| c.visible);
        let moved = |delta| CursorMoved {
            window,
            position: Vec2::splat(10.0),
            delta,
        };
        app.world_mut().write_message(UiNav {
            action: NavAction::Down,
            slot: None,
            device: DeviceKind::Gamepad,
            repeat: false,
        });
        app.update();
        assert_eq!(visible(&app), Some(false), "hidden after pad navigation");
        app.world_mut().write_message(moved(None));
        app.update();
        assert_eq!(
            visible(&app),
            Some(false),
            "entering the window is not motion"
        );
        app.world_mut()
            .write_message(moved(Some(Vec2::new(3.0, 0.0))));
        app.update();
        assert_eq!(visible(&app), Some(true), "shown once the mouse moves");
    }
}
