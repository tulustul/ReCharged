//! `ui.*` channels: readiness and render errors of the React app, UI sound cues and music
//! stingers, menu navigation (`ui.nav`) and toasts, plus the readiness watchdog.

use bevy::prelude::*;
use bevy_react::prelude::*;
use rc_core::prelude::*;
use rc_game::GameNotice;

use crate::input::UiDeviceKind;
use crate::profile::{UiUnlockedItem, Unlocked};

/// `ui.ready` must arrive this many seconds after start, or the run is reported as broken.
pub const READY_TIMEOUT_SECS: f32 = 15.0;

/// The same cue within this many seconds plays once (a fast pointer sweep over a list).
const CUE_RETRIGGER_SECS: f64 = 0.04;

/// React → Bevy message `ui.ready`: the React app mounted (again after a full hot reload).
#[react_message(name = "ui.ready")]
pub struct UiReady;

/// React → Bevy message `ui.error`: the top-level ErrorBoundary caught a render error.
#[react_message(name = "ui.error")]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
pub struct UiError {
    /// Error message.
    pub message: String,
    /// Component stack, if React provided one.
    #[ts(optional)]
    pub stack: Option<String>,
}

mirror_enum!(
    /// [`UiCue`]: a UI sound.
    UiCueName = UiCue { Hover, Select, Back, Toggle, SliderTick, Error, Unlock }
);

/// React → Bevy message `ui.sound`: play a UI cue (focus, confirm, back, toggle, …).
#[react_message(name = "ui.sound")]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
pub struct PlayCue {
    /// The cue.
    pub cue: UiCueName,
}

/// A music stinger the UI times (the Cup-end ceremony).
#[derive(serde::Deserialize, ts_rs::TS, Debug, Clone, Copy, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
pub enum UiStinger {
    /// 2nd or 3rd in the cup.
    PodiumFanfare,
    /// Won the cup.
    CupVictory,
}

/// React → Bevy message `ui.stinger`: play a music stinger (`MusicStinger`).
#[react_message(name = "ui.stinger")]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
pub struct PlayStinger {
    /// The stinger.
    pub stinger: UiStinger,
}

mirror_enum!(
    /// [`NavAction`]: one menu navigation step.
    UiNavAction = NavAction { Up, Down, Left, Right, Confirm, Back, PrevTab, NextTab }
);

/// Bevy → React event `ui.nav`: a menu navigation step (rc_input's `UiNav`). The only source of
/// keyboard/gamepad navigation in React.
#[react_event(name = "ui.nav")]
#[serde(rename_all = "camelCase")]
#[ts(rename_all = "camelCase")]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct NavEvent {
    /// The step.
    pub action: UiNavAction,
    /// Player slot 0–3 (`null` = a device not assigned to a slot, e.g. before joining).
    pub slot: Option<u8>,
    /// Device family (button glyphs follow it).
    pub device: UiDeviceKind,
    /// Generated by hold-repeat.
    pub repeat: bool,
}

impl From<&UiNav> for NavEvent {
    fn from(nav: &UiNav) -> Self {
        Self {
            action: nav.action.into(),
            slot: nav.slot.map(|s| s.0),
            device: nav.device.into(),
            repeat: nav.repeat,
        }
    }
}

/// Bevy → React event `toast`: rc_game's notices (unlocks travel as `profile.unlocked`). React
/// owns the wording and shows errors and disconnects as dialogs, the rest as toasts.
#[react_event(name = "toast")]
#[serde(tag = "kind", rename_all = "camelCase")]
#[ts(tag = "kind", rename_all = "camelCase")]
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum UiNotice {
    /// A Golden Battery was collected (and saved).
    GoldenBattery {
        /// Track id.
        track: String,
    },
    /// A layout's records were set on another version of the track and were discarded.
    RecordsDiscarded {
        /// Track id.
        track: String,
        /// Reverse layout.
        reverse: bool,
        /// Mirrored.
        mirror: bool,
    },
    /// A player's controller disconnected; the race is paused.
    ControllerDisconnected {
        /// Slot 0–3.
        slot: u8,
    },
    /// A race could not start or load, or data is broken; the game is in the menu.
    Error {
        /// What went wrong (file, field).
        detail: String,
    },
    /// A save failed (retried with the next save).
    SaveFailed {
        /// The cause.
        detail: String,
    },
    /// A corrupt save was moved aside and defaults are used.
    SaveRestored {
        /// The corrupt file.
        file: String,
        /// Where it was moved.
        backup: Option<String>,
    },
}

/// Health of the React UI; automation runs exit non-zero when it is not ready or has errors.
#[derive(Resource, Debug, Clone, Default, PartialEq, Eq)]
pub struct UiStatus {
    /// `ui.ready` arrived.
    pub ready: bool,
    /// `ui.error` messages received.
    pub errors: u32,
}

pub(crate) fn register(app: &mut App) {
    app.add_react_handler(on_ready)
        .add_react_handler(on_error)
        .add_react_handler(on_cue)
        .add_react_handler(
            |stinger: On<PlayStinger>, mut out: MessageWriter<MusicStinger>| {
                out.write(MusicStinger(match stinger.event().stinger {
                    UiStinger::PodiumFanfare => MusicCue::PodiumFanfare,
                    UiStinger::CupVictory => MusicCue::CupVictory,
                }));
            },
        )
        .add_react_event::<NavEvent>()
        .add_react_event::<UiNotice>();
}

fn on_ready(_: On<UiReady>, status: Option<ResMut<UiStatus>>) {
    if let Some(mut status) = status {
        if !status.ready {
            info!("UI ready");
        }
        status.ready = true;
    }
}

fn on_error(error: On<UiError>, status: Option<ResMut<UiStatus>>) {
    let error = error.event();
    error!(
        "UI error: {}\n{}",
        error.message,
        error.stack.as_deref().unwrap_or("")
    );
    if let Some(mut status) = status {
        status.errors += 1;
    }
}

fn on_cue(
    cue: On<PlayCue>,
    time: Res<Time<Real>>,
    mut last: Local<Vec<(UiCue, f64)>>,
    mut out: MessageWriter<UiSound>,
) {
    let cue = UiCue::from(cue.event().cue);
    let now = time.elapsed_secs_f64();
    match last.iter_mut().find(|(c, _)| *c == cue) {
        Some((_, at)) if now - *at < CUE_RETRIGGER_SECS => return,
        Some((_, at)) => *at = now,
        None => last.push((cue, now)),
    }
    out.write(UiSound(cue));
}

/// Forwards rc_input's `UiNav` to React as `ui.nav`.
pub(crate) fn forward_nav(mut navs: MessageReader<UiNav>, events: ReactEvents) {
    for nav in navs.read() {
        events.send(&NavEvent::from(nav));
    }
}

/// Forwards rc_game's notices: unlocks as one `profile.unlocked` per frame, the rest as `toast`.
/// Boot-time notices arrive before React listens, so everything waits for `ui.ready`.
pub(crate) fn forward_notices(
    mut notices: MessageReader<GameNotice>,
    status: Res<UiStatus>,
    mut held: Local<Vec<GameNotice>>,
    events: ReactEvents,
) {
    held.extend(notices.read().cloned());
    if !status.ready || held.is_empty() {
        return;
    }
    let mut unlocked = Vec::new();
    for notice in std::mem::take(&mut *held) {
        let toast = match notice {
            GameNotice::Unlocked(content) => {
                unlocked.push(UiUnlockedItem::from(&content));
                continue;
            }
            GameNotice::GoldenBattery(track) => UiNotice::GoldenBattery { track: track.0 },
            GameNotice::RecordsDiscarded(variant) => UiNotice::RecordsDiscarded {
                track: variant.track.0,
                reverse: variant.reverse,
                mirror: variant.mirror,
            },
            GameNotice::ControllerDisconnected(slot) => {
                UiNotice::ControllerDisconnected { slot: slot.0 }
            }
            GameNotice::Error(detail) => UiNotice::Error { detail },
            GameNotice::SaveFailed(detail) => UiNotice::SaveFailed { detail },
            GameNotice::SaveRestored { file, backup } => UiNotice::SaveRestored { file, backup },
        };
        events.send(&toast);
    }
    if !unlocked.is_empty() {
        events.send(&Unlocked { items: unlocked });
    }
}

/// Logs an error (and ends automated runs with a failure) when `ui.ready` is late.
pub(crate) fn watchdog(
    time: Res<Time<Real>>,
    status: Res<UiStatus>,
    automation: Option<Res<AutomationConfig>>,
    mut reported: Local<bool>,
    mut exit: MessageWriter<AppExit>,
) {
    if status.ready || *reported || time.elapsed_secs() < READY_TIMEOUT_SECS {
        return;
    }
    *reported = true;
    error!(
        "ui.ready did not arrive within {READY_TIMEOUT_SECS} s (UI bundle missing, threw, or not mounted)"
    );
    if automation.is_some_and(|a| a.is_automated()) {
        exit.write(AppExit::error());
    }
}
